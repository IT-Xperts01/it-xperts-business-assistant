-- Run once in the Supabase SQL Editor for the project connected to IT Xperts.
-- Workspace data is isolated by authenticated user ID. Daily recovery copies
-- and pre-restore copies are retained for recovery.

create table if not exists public.business_workspaces (
  user_id uuid primary key references auth.users (id) on delete cascade,
  data jsonb not null,
  updated_at timestamptz not null default now(),
  constraint business_workspaces_data_is_object
    check (jsonb_typeof(data) = 'object'),
  constraint business_workspaces_data_size
    check (octet_length(data::text) <= 1048576)
);

create table if not exists public.business_workspace_backups (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  data jsonb not null,
  snapshot_date date default ((now() at time zone 'UTC')::date),
  reason text not null default 'daily'
    check (reason in ('initial', 'daily', 'before-restore')),
  created_at timestamptz not null default now(),
  constraint business_workspace_backups_one_daily_copy_per_day
    unique (user_id, snapshot_date),
  constraint business_workspace_backups_data_is_object
    check (jsonb_typeof(data) = 'object'),
  constraint business_workspace_backups_data_size
    check (octet_length(data::text) <= 1048576)
);

alter table public.business_workspace_backups
  drop constraint if exists business_workspace_backups_one_daily_copy_per_day;
alter table public.business_workspace_backups
  drop constraint if exists business_workspace_backups_one_copy_per_day_and_reason;
alter table public.business_workspace_backups
  add constraint business_workspace_backups_one_copy_per_day_and_reason
  unique (user_id, snapshot_date, reason);

create index if not exists business_workspace_backups_owner_created_idx
  on public.business_workspace_backups (user_id, created_at desc, id desc);

alter table public.business_workspaces enable row level security;
alter table public.business_workspace_backups enable row level security;

drop policy if exists "workspace owner manages own records" on public.business_workspaces;
drop policy if exists "workspace owner reads own records" on public.business_workspaces;
drop policy if exists "workspace owner creates own records" on public.business_workspaces;
drop policy if exists "workspace owner updates own records" on public.business_workspaces;
create policy "workspace owner reads own records"
  on public.business_workspaces
  for select
  to authenticated
  using ((select auth.uid()) = user_id);

create policy "workspace owner creates own records"
  on public.business_workspaces
  for insert
  to authenticated
  with check ((select auth.uid()) = user_id);

create policy "workspace owner updates own records"
  on public.business_workspaces
  for update
  to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

drop policy if exists "workspace owner reads own recovery copies" on public.business_workspace_backups;
create policy "workspace owner reads own recovery copies"
  on public.business_workspace_backups
  for select
  to authenticated
  using ((select auth.uid()) = user_id);

revoke all on public.business_workspaces from anon, public, authenticated;
revoke all on public.business_workspace_backups from anon, public, authenticated;
grant select, insert, update on public.business_workspaces to authenticated;
grant select on public.business_workspace_backups to authenticated;

create or replace function public.keep_business_workspace_recovery_copy()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.business_workspace_backups (user_id, data, snapshot_date, reason)
    values (new.user_id, new.data, (pg_catalog.now() at time zone 'UTC')::date, 'initial')
    on conflict (user_id, snapshot_date, reason) do nothing;
  elsif old.data is distinct from new.data then
    -- Reject accidental full or partial history loss for real workspaces.
    -- Demo/sample data can still be cleared intentionally.
    if not coalesce(old.data->>'isDemo' = 'true', false) then
      if jsonb_array_length(coalesce(old.data->'sales', '[]'::jsonb)) > jsonb_array_length(coalesce(new.data->'sales', '[]'::jsonb))
        or jsonb_array_length(coalesce(old.data->'expenses', '[]'::jsonb)) > jsonb_array_length(coalesce(new.data->'expenses', '[]'::jsonb))
        or jsonb_array_length(coalesce(old.data->'items', '[]'::jsonb)) > jsonb_array_length(coalesce(new.data->'items', '[]'::jsonb))
        or jsonb_array_length(coalesce(old.data->'invoices', '[]'::jsonb)) > jsonb_array_length(coalesce(new.data->'invoices', '[]'::jsonb)) then
        raise exception 'Workspace save rejected because it would remove existing records.';
      end if;

      if exists (
        select 1
        from jsonb_array_elements(coalesce(old.data->'items', '[]'::jsonb)) as old_item(value)
        where not exists (
          select 1
          from jsonb_array_elements(coalesce(new.data->'items', '[]'::jsonb)) as new_item(value)
          where new_item.value->>'name' = old_item.value->>'name'
            and new_item.value->>'type' = old_item.value->>'type'
        )
      ) or exists (
        select 1
        from jsonb_array_elements(coalesce(old.data->'sales', '[]'::jsonb)) as old_sale(value)
        where not exists (
          select 1
          from jsonb_array_elements(coalesce(new.data->'sales', '[]'::jsonb)) as new_sale(value)
          where new_sale.value = old_sale.value
        )
      ) or exists (
        select 1
        from jsonb_array_elements(coalesce(old.data->'expenses', '[]'::jsonb)) as old_expense(value)
        where not exists (
          select 1
          from jsonb_array_elements(coalesce(new.data->'expenses', '[]'::jsonb)) as new_expense(value)
          where new_expense.value = old_expense.value
        )
      ) or exists (
        select 1
        from jsonb_array_elements(coalesce(old.data->'invoices', '[]'::jsonb)) as old_invoice(value)
        where not exists (
          select 1
          from jsonb_array_elements(coalesce(new.data->'invoices', '[]'::jsonb)) as new_invoice(value)
          where new_invoice.value->>'number' = old_invoice.value->>'number'
        )
      ) then
        raise exception 'Workspace save rejected because it would replace existing records.';
      end if;
    end if;

    insert into public.business_workspace_backups (user_id, data, snapshot_date, reason)
    values (old.user_id, old.data, (pg_catalog.now() at time zone 'UTC')::date, 'daily')
    on conflict (user_id, snapshot_date, reason) do nothing;
  end if;

  return new;
end;
$$;

revoke execute on function public.keep_business_workspace_recovery_copy()
  from public, anon, authenticated;

drop trigger if exists business_workspace_recovery_copy on public.business_workspaces;
create trigger business_workspace_recovery_copy
  after insert or update on public.business_workspaces
  for each row
  execute function public.keep_business_workspace_recovery_copy();

create or replace function public.save_business_workspace_before_restore()
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  owner_id uuid := auth.uid();
  workspace_data jsonb;
  recovery_id bigint;
begin
  if owner_id is null then
    raise exception 'Sign-in is required.';
  end if;

  select w.data into workspace_data
  from public.business_workspaces as w
  where w.user_id = owner_id
  for update;

  if workspace_data is null then
    raise exception 'No saved business workspace was found.';
  end if;

  insert into public.business_workspace_backups (user_id, data, snapshot_date, reason)
  values (owner_id, workspace_data, null, 'before-restore')
  returning id into recovery_id;

  return recovery_id;
end;
$$;

revoke execute on function public.save_business_workspace_before_restore()
  from public, anon, authenticated;
grant execute on function public.save_business_workspace_before_restore()
  to authenticated;

